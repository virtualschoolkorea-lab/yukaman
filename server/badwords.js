const LEET = s => s.replace(/[@4]/g, 'a').replace(/0/g, 'o').replace(/[1!|]/g, 'i').replace(/3/g, 'e').replace(/[$5]/g, 's');
const stripMarks = s => s.replace(/[^\p{L}\p{N}]/gu, '');
// 한글 사이에 끼운 숫자·영문·모음을 뺀다: 시1발 → 시발, 씨x발 → 씨발, 시ㅡ발 → 시발
const stripInside = s => s.replace(/(?<=[가-힣ㄱ-ㅎ])[0-9a-z]+(?=[가-힣ㄱ-ㅎ])/g, '').replace(/(?<=[가-힣ㄱ-ㅎ])[ㅏ-ㅣ]+(?=[가-힣ㄱ-ㅎ])/g, '');
const squeeze = s => s.replace(/(.)\1+/gu, '$1');   // 씨이이발 → 씨이발, ㅅㅅㅂㅂ → ㅅㅂ

function candidates(text) {
  // NFKC를 쓰면 ㅅㅂ 같은 자음이 다른 글자로 바뀌어 NFC와 전각 영숫자 바꾸기만 쓴다
  let t = String(text == null ? '' : text).normalize('NFC').replace(/[！-～]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0)).toLowerCase().replace(/[\p{Cf}]/gu, '');
  for (const re of SAFE) t = t.replace(re, ' ');
  const raw = t.split(/\s+/).filter(x => x && !/^https?:/.test(x));
  const toks = raw.map(x => stripMarks(/[a-z]/.test(x) && !/[가-힣ㄱ-ㅎ]/.test(x) ? LEET(x) : x)).filter(Boolean);
  const out = toks.slice();
  // 한 글자씩 띄워 쓴 것을 붙인다: 시 발 · ㅅ ㅂ · 개 새 끼
  for (let i = 0; i < toks.length;) {
    let j = i; let run = '';
    while (j < toks.length && Array.from(toks[j]).length === 1) { run += toks[j]; j++; }
    if (j - i > 1) out.push(run);
    i = j > i ? j : i + 1;
  }
  // 앞 글자만 띄운 것: 씨 발놈 · 시 발새끼
  for (let i = 0; i + 1 < toks.length; i++) if (/^[씨시쉬슈쓰]$/.test(toks[i])) out.push(toks[i] + toks[i + 1]);
  return out;
}

// 막을 말을 찾으면 그 말을, 없으면 빈 문자열을 돌려준다
export function findBadWord(text) {
  for (const tok of candidates(text)) {
    for (const form of [tok, stripInside(tok), squeeze(stripInside(tok))]) {
      if (EXACT.has(form)) return form;
      for (const w of WORDS) if (form.includes(w)) return w;
      for (const re of PATTERNS) { const m = form.match(re); if (m) return m[0]; }
    }
  }
  return '';
}
